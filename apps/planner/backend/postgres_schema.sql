CREATE FUNCTION reject_immutable_change() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    RAISE EXCEPTION 'Immutable %', TG_TABLE_NAME USING ERRCODE = '23514';
END;
$$;

CREATE TRIGGER immutable_reports BEFORE UPDATE OR DELETE OR TRUNCATE ON reports FOR EACH STATEMENT EXECUTE FUNCTION reject_immutable_change();

CREATE TRIGGER immutable_audit BEFORE UPDATE OR DELETE OR TRUNCATE ON audit FOR EACH STATEMENT EXECUTE FUNCTION reject_immutable_change();

CREATE TRIGGER immutable_system_audit BEFORE UPDATE OR DELETE OR TRUNCATE ON system_audit FOR EACH STATEMENT EXECUTE FUNCTION reject_immutable_change();
