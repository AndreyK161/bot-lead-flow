-- PostgreSQL 16 Planner schema v8. Applied only to an empty planner namespace.
-- Keep IDs, timestamps and flags compatible with SQLite export; Telegram IDs require BIGINT.

CREATE TABLE employees (
        id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, telegram_id BIGINT UNIQUE CHECK(telegram_id > 0),
        bitrix_id BIGINT UNIQUE CHECK(bitrix_id > 0), name TEXT NOT NULL,
        role TEXT NOT NULL CHECK(role IN ('manager','supervisor')), active BIGINT NOT NULL DEFAULT 1);

CREATE TABLE plans (
        id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, employee_id BIGINT NOT NULL REFERENCES employees(id), day TEXT NOT NULL,
        status TEXT NOT NULL DEFAULT 'draft' CHECK(status IN ('draft','approved','closed')),
        initial_snapshot TEXT, created_at BIGINT NOT NULL, approved_at BIGINT, approved_by BIGINT REFERENCES employees(id),
        closed_at BIGINT, UNIQUE(employee_id, day), UNIQUE(id, employee_id));

CREATE TABLE tasks (
        id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, plan_id BIGINT NOT NULL, employee_id BIGINT NOT NULL,
        title TEXT NOT NULL, description TEXT NOT NULL DEFAULT '',
        kind TEXT NOT NULL CHECK(kind IN ('quantitative','general','client','bitrix')),
        planned_minutes BIGINT NOT NULL DEFAULT 0 CHECK(planned_minutes >= 0), target DOUBLE PRECISION,
        actual_value DOUBLE PRECISION NOT NULL DEFAULT 0, actual_seconds BIGINT NOT NULL DEFAULT 0 CHECK(actual_seconds >= 0),
        timer_started BIGINT, status TEXT NOT NULL DEFAULT 'todo' CHECK(status IN ('todo','in_progress','done','moved')),
        result TEXT NOT NULL DEFAULT '', comment TEXT NOT NULL DEFAULT '',
        created_by BIGINT NOT NULL REFERENCES employees(id), locked BIGINT NOT NULL DEFAULT 0,
        revision BIGINT NOT NULL DEFAULT 1, created_at BIGINT NOT NULL,
        moved_to BIGINT REFERENCES tasks(id), source_task_id BIGINT REFERENCES tasks(id),
        external_id TEXT, external_url TEXT, external_status TEXT, work_done_today BIGINT NOT NULL DEFAULT 0,
        deadline_outcome TEXT CHECK(deadline_outcome IN ('work_done_and_moved','deadline_only')),
        FOREIGN KEY(plan_id, employee_id) REFERENCES plans(id, employee_id));

CREATE UNIQUE INDEX one_timer_per_employee ON tasks(employee_id) WHERE timer_started IS NOT NULL;

CREATE INDEX tasks_plan ON tasks(plan_id);

CREATE TABLE goal_requests (
        id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, task_id BIGINT NOT NULL REFERENCES tasks(id),
        employee_id BIGINT NOT NULL REFERENCES employees(id), field TEXT NOT NULL CHECK(field IN ('target','planned_minutes')),
        old_value DOUBLE PRECISION, proposed DOUBLE PRECISION NOT NULL, reason TEXT NOT NULL,
        status TEXT NOT NULL DEFAULT 'pending' CHECK(status IN ('pending','approved','rejected','cancelled')),
        created_at BIGINT NOT NULL, decided_at BIGINT, decided_by BIGINT REFERENCES employees(id), decision_comment TEXT NOT NULL DEFAULT '');

CREATE UNIQUE INDEX one_pending_goal ON goal_requests(task_id,field) WHERE status='pending';

CREATE TABLE audit (
        id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, plan_id BIGINT REFERENCES plans(id), entity TEXT NOT NULL, entity_id BIGINT NOT NULL,
        actor_id BIGINT NOT NULL REFERENCES employees(id), action TEXT NOT NULL,
        before_json TEXT, after_json TEXT, created_at BIGINT NOT NULL);

CREATE INDEX audit_plan ON audit(plan_id,id);

CREATE TABLE reports (
        plan_id BIGINT PRIMARY KEY REFERENCES plans(id), snapshot TEXT NOT NULL, closed_by BIGINT NOT NULL REFERENCES employees(id),
        created_at BIGINT NOT NULL);

ALTER TABLE tasks ADD COLUMN creation_actor TEXT NOT NULL DEFAULT 'employee' CHECK(creation_actor IN ('employee','system'));

CREATE TABLE distributions(id TEXT PRIMARY KEY,workday TEXT NOT NULL UNIQUE,sha256 TEXT NOT NULL,payload TEXT NOT NULL,status TEXT NOT NULL CHECK(status IN ('imported','review')),reason TEXT NOT NULL,imported_at BIGINT NOT NULL);

CREATE TABLE distribution_tasks(distribution_id TEXT NOT NULL REFERENCES distributions(id),employee_id BIGINT NOT NULL REFERENCES employees(id),task_id BIGINT UNIQUE REFERENCES tasks(id),status TEXT NOT NULL CHECK(status IN ('imported','review')),PRIMARY KEY(distribution_id,employee_id));

CREATE TABLE distribution_leads(distribution_id TEXT NOT NULL REFERENCES distributions(id),lead_id BIGINT NOT NULL,employee_id BIGINT NOT NULL REFERENCES employees(id),created_date TEXT NOT NULL,initial_stage TEXT NOT NULL CHECK(initial_stage='IN_PROCESS'),PRIMARY KEY(distribution_id,lead_id));

CREATE TABLE system_audit(id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,plan_id BIGINT REFERENCES plans(id),entity TEXT NOT NULL,entity_id BIGINT NOT NULL,action TEXT NOT NULL,after_json TEXT NOT NULL,created_at BIGINT NOT NULL);

CREATE TABLE schema_migrations(version BIGINT PRIMARY KEY,applied_at BIGINT NOT NULL,details TEXT NOT NULL);

CREATE TABLE import_attempts(id TEXT PRIMARY KEY,status TEXT NOT NULL CHECK(status IN ('imported','review','error')),attempts BIGINT NOT NULL,last_attempt BIGINT NOT NULL,error_code TEXT NOT NULL);

CREATE INDEX external_tasks_id ON tasks(external_id) WHERE external_id IS NOT NULL;

CREATE TABLE legacy_imports(source_sha256 TEXT PRIMARY KEY,imported_at BIGINT NOT NULL,manifest_json TEXT NOT NULL);

CREATE TABLE employee_aliases(telegram_id BIGINT PRIMARY KEY CHECK(telegram_id > 0),employee_id BIGINT NOT NULL REFERENCES employees(id));

CREATE TABLE storage_metadata(singleton SMALLINT PRIMARY KEY CHECK(singleton=1),application TEXT NOT NULL CHECK(application='leadflow-planner'),version BIGINT NOT NULL);

